create schema if not exists recipe_catalog;

revoke all on schema recipe_catalog from public, anon, authenticated;

create table recipe_catalog.recipes (
  recipe_id text primary key,
  source text not null,
  source_name text not null,
  source_dataset text not null,
  source_recipe_id text not null,
  name text not null,
  summary text,
  cuisine text,
  category text not null,
  cooking_method text,
  cooking_time text,
  servings text,
  difficulty text,
  estimated_cost text,
  main_ingredient_category text,
  weight_g numeric,
  kcal numeric,
  carbs_g numeric,
  protein_g numeric,
  fat_g numeric,
  sodium_mg numeric,
  hashtag text,
  image_main_url text,
  image_cooking_url text,
  tip text,
  ingredients_raw text not null
);

create table recipe_catalog.ingredients (
  id bigint generated by default as identity primary key,
  recipe_id text not null
    references recipe_catalog.recipes(recipe_id) on delete cascade,
  source text not null,
  source_recipe_id text not null,
  ingredient_no integer not null,
  ingredient_group text not null,
  ingredient_raw text not null,
  ingredient_name text not null,
  normalized_name text not null,
  parent_ingredient text,
  amount text,
  search_key text not null,
  parse_status text not null,
  unique (recipe_id, ingredient_no)
);

create table recipe_catalog.steps (
  id bigint generated by default as identity primary key,
  recipe_id text not null
    references recipe_catalog.recipes(recipe_id) on delete cascade,
  source text not null,
  source_recipe_id text not null,
  step_no integer not null,
  source_step_no text not null,
  description text not null,
  description_raw text not null,
  image_url text,
  step_tip text,
  unique (recipe_id, step_no)
);

create index recipes_name_idx
  on recipe_catalog.recipes(name);

create index ingredients_recipe_id_idx
  on recipe_catalog.ingredients(recipe_id);

create index ingredients_normalized_name_recipe_id_idx
  on recipe_catalog.ingredients(normalized_name, recipe_id);

create index ingredients_parent_ingredient_recipe_id_idx
  on recipe_catalog.ingredients(parent_ingredient, recipe_id)
  where parent_ingredient is not null;

create index ingredients_search_key_recipe_id_idx
  on recipe_catalog.ingredients(search_key, recipe_id);

create index steps_recipe_id_idx
  on recipe_catalog.steps(recipe_id);

alter table recipe_catalog.recipes enable row level security;
alter table recipe_catalog.ingredients enable row level security;
alter table recipe_catalog.steps enable row level security;

revoke all on table
  recipe_catalog.recipes,
